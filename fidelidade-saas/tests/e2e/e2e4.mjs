import { chromium } from 'playwright-core';
import { execSync } from 'node:child_process';
import assert from 'node:assert/strict';
const BASE='http://localhost:3000';
const sql=(q)=>execSync(`psql postgresql://postgres:postgres@localhost:5432/fidelidade -At -c ${JSON.stringify(q)}`).toString().trim();
sql('TRUNCATE "RateLimit"'); sql('delete from "Notification"'); sql('update "Wallet" set balance=100');
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox'] });
const wait=(p,t)=>p.waitForTimeout(t);
const o = await (await browser.newContext({viewport:{width:1280,height:900}})).newPage();
await o.goto(BASE+'/login'); await wait(o,2500);
await o.fill('#email','ze@burger.com'); await o.fill('#password','senha-segura-1');
await o.click('button[type=submit]:has-text("Entrar")'); await o.waitForURL('**/dashboard');
await o.goto(BASE+'/dashboard/caixa'); await wait(o,2500);
await o.fill('#amount','20,00');
await o.click('text=Gerar QR Code'); await o.waitForSelector('text=Enviar por WhatsApp');
const token=sql('select token from "Claim" order by "createdAt" desc limit 1');

const cctx = await browser.newContext({viewport:{width:390,height:844},isMobile:true});
await cctx.addInitScript(()=>localStorage.setItem('fz_intro_v1','1'));
const c = await cctx.newPage();
await c.goto(BASE+'/entrar'); await wait(c,2500);
await c.fill('#c-email','lucas@teste.com'); await c.fill('#c-password','senha-cliente-1');
await c.click('button[type=submit]'); await c.waitForURL('**/carteira**');
await c.goto(BASE+'/r/'+token); await wait(c,2500);
await c.click('text=Receber meus pontos'); await c.waitForURL('**/carteira/*?credited=1');
const rows = sql(`select title||' | '||body from "Notification" order by "createdAt"`);
console.log(rows);
assert.match(rows, /\+200 pontos/);
assert.match(rows, /Faltam 200 pontos para Sobremesa/);
console.log('1. aviso criado ao receber pontos OK');
await c.goto(BASE+'/carteira'); await wait(c,2500);
await c.locator('[aria-label$="aviso novo"]:visible').first().waitFor();
console.log('2. bolinha no menu OK');
await c.screenshot({path:'av-home.png'});
await c.click('nav a[href="/avisos"]:visible'); await c.waitForURL('**/avisos'); await wait(c,500);
await c.screenshot({path:'av-avisos.png', fullPage:true});
await wait(c,3000);
assert.notEqual(sql(`select count(*) from "Notification" where "readAt" is null`),'0'); // só abrir a tela não marca nada
await c.locator('[data-testid=notice-day] button[aria-expanded=false]').evaluateAll((bs) => bs.forEach((b) => b.click()));
await wait(c,3000);
assert.equal(sql(`select count(*) from "Notification" where "readAt" is null`),'0');
await c.reload(); await wait(c,1500);
assert.equal(await c.locator('[aria-label$="aviso novo"]:visible, [aria-label$="avisos novos"]:visible').count(),0);
console.log('3. abrir as datas dos avisos marca como lido e some a bolinha OK');
const dctx = await browser.newContext({viewport:{width:1366,height:768}});
await dctx.addInitScript(()=>localStorage.setItem('fz_intro_v1','1'));
const d = await dctx.newPage();
await d.goto(BASE+'/entrar'); await wait(d,2500);
await d.fill('#c-email','lucas@teste.com'); await d.fill('#c-password','senha-cliente-1');
